    @NonNull
    public static ColorScheme getColorScheme(@NonNull Context context, @Nullable String id) {
        List<ColorScheme> schemes = getColorSchemes(context);
        for (ColorScheme scheme : schemes) {
            if (scheme.id.equals(id) && scheme.available) return scheme;
        }
        return schemes.get(1); // Classic
    }

    /** The scheme selected by default: Material You if available, otherwise Catppuccin. */
    @NonNull
    public static String getDefaultColorSchemeId() {
        return Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ? SCHEME_MATERIAL_YOU : SCHEME_CATPPUCCIN;
    }

    @NonNull
    private static ColorScheme getMaterialYouScheme(@NonNull Context context) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S)
            return buildMaterialYouScheme(context);

        // Placeholder so that the option is shown as unavailable.
        int[] ansi = new int[16];
        for (int i = 0; i < 16; i++) ansi[i] = Color.GRAY;
        return new ColorScheme(SCHEME_MATERIAL_YOU, R.string.scheme_material_you, R.string.scheme_material_you_unavailable,
            ansi, Color.WHITE, Color.BLACK, Color.WHITE, false);
    }

    /**
     * Build a dark terminal palette from the system dynamic (wallpaper) colors. Neutral tones are
     * used for the background and text, accent tones for blue/magenta/cyan and the cursor, and the
     * remaining ANSI colors are classic hues harmonized towards the primary accent so that `ls`,
     * `git diff` etc. still look like red/green/yellow but match the wallpaper.
     */
    @RequiresApi(api = Build.VERSION_CODES.S)
    @NonNull
    private static ColorScheme buildMaterialYouScheme(@NonNull Context context) {
        int accent = context.getColor(android.R.color.system_accent1_500);

        int red = MaterialColors.harmonize(0xfff2777a, accent);
        int green = MaterialColors.harmonize(0xff99cc99, accent);
        int yellow = MaterialColors.harmonize(0xffffcc66, accent);

        int[] ansi = new int[]{
            context.getColor(android.R.color.system_neutral2_800),  // black
            red,
            green,
            yellow,
            context.getColor(android.R.color.system_accent1_200),   // blue -> primary
            context.getColor(android.R.color.system_accent3_200),   // magenta -> tertiary
            context.getColor(android.R.color.system_accent2_200),   // cyan -> secondary
            context.getColor(android.R.color.system_neutral1_200),  // white
            context.getColor(android.R.color.system_neutral2_500),  // bright black
            lighten(red),
            lighten(green),
            lighten(yellow),
            context.getColor(android.R.color.system_accent1_100),
            context.getColor(android.R.color.system_accent3_100),
            context.getColor(android.R.color.system_accent2_100),
            context.getColor(android.R.color.system_neutral1_50),   // bright white
        };

        return new ColorScheme(SCHEME_MATERIAL_YOU, R.string.scheme_material_you, R.string.scheme_material_you_desc, ansi,
            context.getColor(android.R.color.system_neutral1_100),
            context.getColor(android.R.color.system_neutral1_900),
            context.getColor(android.R.color.system_accent1_200),
            true);
    }

    private static int lighten(int color) {
        return ColorUtils.blendARGB(color, Color.WHITE, 0.25f);
    }

    private static String hex(int color) {
        return String.format(Locale.ROOT, "#%06x", color & 0xffffff);
    }



    @NonNull
    public static Typeface getTypeface(@NonNull Context context, @Nullable String fontId) {
        if (FONT_JETBRAINS_MONO.equals(fontId)) {
            try {
                return Typeface.createFromAsset(context.getAssets(), FONT_JETBRAINS_MONO_ASSET);
            } catch (RuntimeException e) {
                Logger.logStackTraceWithMessage(LOG_TAG, "Failed to load the JetBrains Mono font", e);
            }
        }
        return Typeface.MONOSPACE;
    }



    /** The user's choices in the setup. */
    public static final class Choices {
        public String colorSchemeId = getDefaultColorSchemeId();
        public String fontId = FONT_JETBRAINS_MONO;
        /** Font size in pixels, or 0 to keep the current size. */
        public int fontSizePx = 0;
        public boolean prompt = true;
        public boolean greeting = true;
    }

    /** Load the choices saved by a previous setup, or the defaults. */
    @NonNull
    public static Choices loadChoices(@NonNull Context context) {
        SharedPreferences preferences = getPreferences(context);
        Choices choices = new Choices();
        choices.colorSchemeId = preferences.getString(KEY_COLOR_SCHEME, choices.colorSchemeId);
        choices.fontId = preferences.getString(KEY_FONT, choices.fontId);
        choices.prompt = preferences.getBoolean(KEY_PROMPT, choices.prompt);
        choices.greeting = preferences.getBoolean(KEY_GREETING, choices.greeting);
        return choices;
    }

    /**
     * Write all the files for the choices. Must be called on a background thread after the bootstrap
     * has been installed.
     */
    public static void apply(@NonNull Context context, @NonNull Choices choices) throws IOException {
        File dataHomeDir = new File(TermuxConstants.TERMUX_DATA_HOME_DIR_PATH);
        if (!dataHomeDir.isDirectory() && !dataHomeDir.mkdirs())
            throw new IOException("Failed to create " + dataHomeDir);

        writeColorScheme(getColorScheme(context, choices.colorSchemeId));
        writeFont(context, choices.fontId);
        writePrompt(choices.prompt);
        writeGreeting(context, choices.greeting);

        if (choices.fontSizePx > 0) {
            TermuxAppSharedPreferences preferences = TermuxAppSharedPreferences.build(context);
            if (preferences != null) preferences.setFontSize(choices.fontSizePx);
        }

        getPreferences(context).edit()
            .putString(KEY_COLOR_SCHEME, choices.colorSchemeId)
            .putString(KEY_FONT, choices.fontId)
            .putBoolean(KEY_PROMPT, choices.prompt)
            .putBoolean(KEY_GREETING, choices.greeting)
            .apply();
    }

    private static void writeColorScheme(@NonNull ColorScheme scheme) throws IOException {
        File colorsFile = TermuxConstants.TERMUX_COLOR_PROPERTIES_FILE;
        if (SCHEME_CLASSIC.equals(scheme.id)) {
            // The built-in defaults are the classic scheme.
            if (colorsFile.exists() && !colorsFile.delete())
                throw new IOException("Failed to delete " + colorsFile);
            return;
        }
        writeFile(colorsFile, scheme.toProperties());
    }

    private static void writeFont(@NonNull Context context, @NonNull String fontId) throws IOException {
        File fontFile = TermuxConstants.TERMUX_FONT_FILE;
        if (!FONT_JETBRAINS_MONO.equals(fontId)) {
            if (fontFile.exists() && !fontFile.delete())
                throw new IOException("Failed to delete " + fontFile);
            return;
        }

        try (InputStream in = context.getAssets().open(FONT_JETBRAINS_MONO_ASSET);
             OutputStream out = new FileOutputStream(fontFile)) {
            byte[] buffer = new byte[16 * 1024];
            int read;
            while ((read = in.read(buffer)) != -1) out.write(buffer, 0, read);
        }
    }

    /** Add or remove the prompt block in ~/.bashrc, keeping everything else the user wrote. */
    private static void writePrompt(boolean enabled) throws IOException {
        String bashrc = BASHRC_FILE.isFile() ? readFile(BASHRC_FILE) : "";

        int start = bashrc.indexOf(BASHRC_BLOCK_START);
        int end = bashrc.indexOf(BASHRC_BLOCK_END);
        if (start != -1 && end > start) {
            int blockEnd = end + BASHRC_BLOCK_END.length();
            if (blockEnd < bashrc.length() && bashrc.charAt(blockEnd) == '\n') blockEnd++;
            bashrc = bashrc.substring(0, start) + bashrc.substring(blockEnd);
        }

        if (enabled) {
            if (!bashrc.isEmpty() && !bashrc.endsWith("\n")) bashrc += "\n";
            bashrc += BASHRC_BLOCK_START + "\n" +
                "# Added by the Termux setup. Delete this block to get the default prompt back.\n" +
                "# Two line prompt: current folder, then a green arrow that turns red if the last command failed.\n" +
                "__termux_setup_prompt() {\n" +
                "    local status=$?\n" +
                "    local arrow='\\[\\e[1;32m\\]'\n" +
                "    [ $status -ne 0 ] && arrow='\\[\\e[1;31m\\]'\n" +
                "    PS1=\"\\n\\[\\e[0;34m\\]\u256d\u2500 \\[\\e[1;34m\\]\\w\\[\\e[0m\\]\\n\\[\\e[0;34m\\]\u2570\u2500${arrow}\u276f\\[\\e[0m\\] \"\n" +
                "}\n" +
                "PROMPT_COMMAND=__termux_setup_prompt\n" +
                BASHRC_BLOCK_END + "\n";
        }

        if (bashrc.isEmpty()) {
            if (BASHRC_FILE.exists() && !BASHRC_FILE.delete())
                throw new IOException("Failed to delete " + BASHRC_FILE);
        } else {
            writeFile(BASHRC_FILE, bashrc);
        }
    }

    /** Write or remove ~/.termux/motd.sh, which the Termux login script runs instead of the default motd. */
    private static void writeGreeting(@NonNull Context context, boolean enabled) throws IOException {
        if (!enabled) {
            // Only remove the greeting if it was written by us.
            if (MOTD_FILE.isFile() && readFile(MOTD_FILE).contains(MARKER) && !MOTD_FILE.delete())
                throw new IOException("Failed to delete " + MOTD_FILE);
            return;
        }

        String script = "#!" + TermuxConstants.TERMUX_BIN_PREFIX_DIR_PATH + "/sh\n" +
            "# Generated by the " + MARKER + ". Delete this file to get the default motd back.\n" +
            "b='\\033[0;34m'; m='\\033[0;35m'; c='\\033[0;36m'; d='\\033[2m'; r='\\033[0m'\n" +
            "printf '\\n'\n" +
            "printf \"  ${b}\u2580\u2588\u2580 \u2588\u2580\u2580 \u2588\u2580\u2588 \u2588\u2580\u2584\u2580\u2588 \u2588 \u2588 \u2580\u2584\u2580${r}\\n\"\n" +
            "printf \"  ${m} \u2588  \u2588\u2588\u2584 \u2588\u2580\u2584 \u2588 \u2580 \u2588 \u2588\u2584\u2588 \u2588 \u2588${r}\\n\"\n" +
            "printf \"  ${d}%s${r}\\n\\n\" " + shellQuote(context.getString(R.string.motd_subtitle)) + "\n" +
            motdCommand("pkg install python", context.getString(R.string.motd_install)) +
            motdCommand("pkg upgrade", context.getString(R.string.motd_upgrade)) +
            motdCommand("termux-setup-storage", context.getString(R.string.motd_storage)) +
            motdCommand("termux-change-repo", context.getString(R.string.motd_change_repo)) +
            "printf '\\n'\n";

        writeFile(MOTD_FILE, script);
        try {
            //noinspection OctalInteger
            Os.chmod(MOTD_FILE.getAbsolutePath(), 0700);
        } catch (Exception e) {
            Logger.logStackTraceWithMessage(LOG_TAG, "Failed to chmod " + MOTD_FILE, e);
        }
    }

    private static String motdCommand(String command, String description) {
        return "printf \"  ${c}%-22s${r}${d}%s${r}\\n\" " + shellQuote(command) + " " + shellQuote(description) + "\n";
    }

    private static String shellQuote(String value) {
        return "'" + value.replace("'", "'\\''") + "'";
    }



    /**
     * Regenerate the Material You colors.properties if that scheme is selected, so that the terminal
     * follows wallpaper changes. Cheap enough to be called whenever the colors are (re)loaded.
     */
    public static void refreshMaterialYouIfSelected(@NonNull Context context) {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.S) return;
        if (!SCHEME_MATERIAL_YOU.equals(getPreferences(context).getString(KEY_COLOR_SCHEME, null))) return;

        try {
            File colorsFile = TermuxConstants.TERMUX_COLOR_PROPERTIES_FILE;
            String properties = buildMaterialYouScheme(context).toProperties();
            if (colorsFile.isFile() && properties.equals(readFile(colorsFile))) return;
            File parent = colorsFile.getParentFile();
            if (parent != null && !parent.isDirectory() && !parent.mkdirs()) return;
            writeFile(colorsFile, properties);
        } catch (IOException e) {
            Logger.logStackTraceWithMessage(LOG_TAG, "Failed to refresh the Material You colors", e);
        }
    }



    /** If the first run setup should be shown: never completed and the bootstrap is not installed yet. */
    public static boolean shouldShowSetup(@NonNull Context context) {
        SharedPreferences preferences = getPreferences(context);
        if (preferences.getBoolean(KEY_SETUP_COMPLETED, false)) return false;

        if (isBootstrapInstalled()) {
            // Existing installation from before the setup existed: do not interrupt the user.
            setSetupCompleted(context);
            return false;
        }
        return true;
    }

    /**
     * If the bootstrap is installed. The prefix may already contain files written by the app itself,
     * like etc/termux/termux.env, before the bootstrap is installed, so those are ignored.
     */
    public static boolean isBootstrapInstalled() {
        return TermuxConstants.TERMUX_PREFIX_DIR.isDirectory() && !TermuxFileUtils.isTermuxPrefixDirectoryEmpty();
    }

    public static void setSetupCompleted(@NonNull Context context) {
        getPreferences(context).edit().putBoolean(KEY_SETUP_COMPLETED, true).apply();
    }

    private static SharedPreferences getPreferences(@NonNull Context context) {
        return context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE);
    }



    private static String readFile(@NonNull File file) throws IOException {
        try (InputStream in = new FileInputStream(file)) {
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            byte[] buffer = new byte[8192];
            int read;
            while ((read = in.read(buffer)) != -1) out.write(buffer, 0, read);
            return new String(out.toByteArray(), StandardCharsets.UTF_8);
        }
    }

    private static void writeFile(@NonNull File file, @NonNull String content) throws IOException {
        File parent = file.getParentFile();
        if (parent != null && !parent.isDirectory() && !parent.mkdirs())
            throw new IOException("Failed to create " + parent);
        try (OutputStream out = new FileOutputStream(file)) {
            out.write(content.getBytes(StandardCharsets.UTF_8));
        }
    }

